"""Validate the generated submission-budget experiment; report observations."""
import argparse
import json
from pathlib import Path
import re

LENGTHS = (0, 1, 35, 36, 37, 0xc1008c48, 0xffffffff)
FIELDS = ('length', 'total', 'available', 'committed', 'reserved', 'cache', 'pool', 'stack', 'image')


def indexed(rows, key, label):
    result = {}
    for row in rows:
        identity = row[key]
        if identity in result:
            raise ValueError(f'duplicate {label} {identity}')
        result[identity] = row
    return result


def analyze(text):
    records = {}
    for line in text.splitlines():
        match = re.search(r'FORZA-PUMP-([A-Z-]+)\s+(.*)', line)
        if not match:
            continue
        kind, fields = match.groups()
        raw = dict(re.findall(r'(\w+)=([^\s]+)', fields))
        row = {}
        for key, value in raw.items():
            if kind == 'META' and key not in ('version', 'frequency', 'seconds', 'cases', 'depth', 'buffers', 'frame_ms'):
                row[key] = value
            else:
                row[key] = int(value, 16 if key == 'status' or (kind == 'MM' and key != 'index') else 10)
        records.setdefault(kind, []).append(row)
    for kind in ('META', 'END'):
        if len(records.get(kind, [])) != 1:
            raise ValueError(f'exactly one {kind} required')
    for kind, rows in records.items():
        if any(row.get('failures', 0) for row in rows):
            raise ValueError(f'{kind} reports failures')
    if records.get('ERROR'):
        raise ValueError('fixture reports ERROR')
    meta = records['META'][0]
    frequency = meta['frequency']
    if frequency <= 0 or meta['seconds'] < 10 or meta['cases'] != 8 or meta['depth'] != 8 or meta['buffers'] != 16 or meta['frame_ms'] != 33:
        raise ValueError('unexpected META matrix or clock')
    queries = indexed(records.get('MM', []), 'index', 'MM')
    if sorted(queries) != list(range(7)):
        raise ValueError('all seven MM observations required')
    for index, row in queries.items():
        if row['input'] != LENGTHS[index] or any(field not in row for field in FIELDS):
            raise ValueError('MM input/fields mismatch')
        for side in ('pre', 'post'):
            for n in range(4):
                if row[f'{side}{n}'] != 0xa5a5a5a5:
                    raise ValueError('MM surrounding canary changed')
    cases = indexed(records.get('CASE', []), 'id', 'CASE')
    timings = indexed(records.get('TIMING', []), 'id', 'TIMING')
    if sorted(cases) != list(range(8)) or sorted(timings) != list(range(8)):
        raise ValueError('eight complete cases/timings required')
    for kind in ('OP', 'FRAME', 'SIZE'):
        if any(row['id'] not in cases for row in records.get(kind, [])):
            raise ValueError(f'{kind} refers to an unknown case')
    for case_id, case in cases.items():
        target, budget = (783 if case_id < 4 else 900), (250, 450, 1000, 0)[case_id % 4]
        if case['target'] != target or case['before'] != target or case['after'] != target or case['budget_us'] != budget:
            raise ValueError('CASE pressure/budget mismatch')
        if case['elapsed'] < frequency * 10:
            raise ValueError('CASE duration below ten seconds')
        operations = case['operations']
        if operations < 2 or operations != case['verified'] or operations != case['callbacks']:
            raise ValueError('CASE callback/verified count mismatch')
        if not 1 <= case['high_water'] <= 8:
            raise ValueError('CASE exceeds depth or lacks outstanding reads')
        if case['bytes'] != ((operations+1)//2)*65536 + (operations//2)*512:
            raise ValueError('CASE generated byte count mismatch')
        sizes = indexed([row for row in records.get('SIZE', []) if row['id'] == case_id], 'bytes', 'SIZE')
        if sorted(sizes) != [512, 65536]:
            raise ValueError('two SIZE observations required')
        for size, row in sizes.items():
            if row['count'] != (operations//2 if size == 512 else (operations+1)//2):
                raise ValueError('SIZE count mismatch')
            for name in ('submit', 'callback'):
                if not 0 <= row[name+'_max'] <= row[name+'_sum']:
                    raise ValueError('SIZE timing bounds mismatch')
                row[name+'_mean_us'] = row[name+'_sum'] * 1000000 / frequency / row['count']
                row[name+'_max_us'] = row[name+'_max'] * 1000000 / frequency
        timing = timings[case_id]
        if not budget and timing['budget_stops']:
            raise ValueError('uncapped case reports budget stops')
        if timing['pair_same'] + timing['pair_split'] != operations//2:
            raise ValueError('pair count mismatch')
        if not (0 <= timing['pending'] <= operations and 0 <= timing['empty_immediate'] <= operations and 0 <= timing['budget_stops'] <= case['frames']):
            raise ValueError('TIMING counts outside observed operations/frames')
        ops = indexed([row for row in records.get('OP', []) if row['id'] == case_id], 'seq', 'OP')
        if sorted(ops) != list(range(min(64, operations))):
            raise ValueError('missing OP samples')
        last_slot = {}
        for seq, row in sorted(ops.items()):
            if row['bytes'] != (512 if seq%2 else 65536) or row['calls'] != 1 or row['status'] not in (0, 0x103):
                raise ValueError('OP size/callback/status failure')
            if not 0 <= row['slot'] < 16 or not 0 <= row['frame'] < case['frames']:
                raise ValueError('OP slot/frame out of range')
            if not 0 < row['burst'] <= row['issue'] <= row['returned'] <= row['callback']:
                raise ValueError('OP timestamp order failure')
            if not row['burst'] <= row['checked'] <= row['issue']:
                raise ValueError('OP deadline check timestamp order')
            if budget and (row['checked']-row['burst'])*1000000 >= frequency*budget:
                raise ValueError('OP deadline check exhausted budget')
            if row['slot'] in last_slot and last_slot[row['slot']]['callback'] > row['burst']:
                raise ValueError('OP early slot reuse before prior callback and outside-pump preparation')
            last_slot[row['slot']] = row
            expected_offset = (((seq//2)*197)%127)*65536 + (65536 if seq%2 else 0)
            if row['offset'] != expected_offset:
                raise ValueError('OP generated offset mismatch')
            if seq and ops[seq-1]['returned'] > row['issue']:
                raise ValueError('OP submission sequence overlaps')
            if seq and budget and ops[seq-1]['frame'] == row['frame'] and (ops[seq-1]['returned']-row['burst'])*1000000 >= frequency*budget:
                raise ValueError('OP issued after prior return exhausted burst budget')
            if seq%2 and row['offset'] != ops[seq-1]['offset']+65536:
                raise ValueError('OP generated pair offset mismatch')
        frames = indexed([row for row in records.get('FRAME', []) if row['id'] == case_id], 'frame', 'FRAME')
        if sorted(frames) != list(range(min(32, case['frames']))):
            raise ValueError('missing FRAME samples')
        issued = 0
        for number, frame in sorted(frames.items()):
            if not (0 < frame['begin'] <= frame['end'] and 0 <= frame['before'] <= 8 and 0 <= frame['after'] <= 8 and 0 <= frame['issued'] <= 8 and 0 <= frame['after_initial'] <= frame['before']):
                raise ValueError('FRAME timestamp/slot count failure')
            if frame['initial_ticks'] + frame['submit_ticks'] + frame['poll_ticks'] > frame['end']-frame['begin']:
                raise ValueError('FRAME measured costs exceed burst span')
            expected_before = frames[number-1]['after'] if number else 0
            if frame['before'] != expected_before:
                raise ValueError('FRAME continuity across nonalertable interval')
            if frame['after'] > frame['after_initial'] + frame['issued']:
                raise ValueError('FRAME creates unexplained outstanding requests')
            if frame['issued'] and frame['after_initial'] == 8:
                raise ValueError('FRAME issues while initial poll leaves queue full')
            if frame['budget_hit'] not in (0, 1) or (not budget and frame['budget_hit']):
                raise ValueError('FRAME invalid/uncapped budget hit')
            if (frame['initial_return']-frame['begin'] != frame['initial_ticks']
                    or not frame['begin'] <= frame['initial_return'] <= frame['end']
                    or frame['initial_callbacks'] != frame['before']-frame['after_initial']):
                raise ValueError('FRAME initial poll accounting')
            if budget and frame['issued'] and frame['initial_ticks']*1000000 >= frequency*budget:
                raise ValueError('FRAME initial poll exhausted budget before issue')
            samples = [row for row in ops.values() if row['frame'] == number]
            expected = min(frame['issued'], max(0, min(64, operations)-issued))
            if len(samples) != expected:
                raise ValueError('FRAME/OP sample count mismatch')
            for row in samples:
                if row['burst'] != frame['begin'] or row['returned'] > frame['end'] or row['checked'] < frame['initial_return']:
                    raise ValueError('FRAME/OP timestamp mismatch')
            issued += frame['issued']
        if (not 0 <= timing['zero_issue_frames'] <= case['frames']
                or not 0 <= timing['initial_callbacks'] <= operations
                or not 0 <= timing['initial_max'] <= timing['initial_sum'] <= timing['burst_sum']
                or timing['initial_sum'] + timing['poll_sum'] + sum(r['submit_sum'] for r in sizes.values()) > timing['burst_sum']):
            raise ValueError('TIMING initial poll costs/counts outside bounds')
        sampled = {'zero_issue_frames': sum(f['issued'] == 0 for f in frames.values()),
                   'budget_stops': sum(f['budget_hit'] for f in frames.values()),
                   'initial_sum': sum(f['initial_ticks'] for f in frames.values()),
                   'initial_callbacks': sum(f['initial_callbacks'] for f in frames.values())}
        if any(timing[key] < value or (case['frames'] <= 32 and timing[key] != value)
               for key, value in sampled.items()):
            raise ValueError('TIMING differs from initial-poll FRAME sample counts')
        unsampled_frames = case['frames']-len(frames)
        if (timing['zero_issue_frames'] > sampled['zero_issue_frames']+unsampled_frames
                or timing['budget_stops'] > sampled['budget_stops']+unsampled_frames
                or timing['initial_callbacks'] > sampled['initial_callbacks']+8*unsampled_frames):
            raise ValueError('TIMING exceeds possible unsampled frame counts')
        case.update(timing)
        case['elapsed_seconds'] = case['elapsed']/frequency
        case['operations_per_second'] = operations/case['elapsed_seconds']
        case['bytes_per_second'] = case['bytes']/case['elapsed_seconds']
        case['mean_issues_per_frame'] = operations/case['frames']
        case['pair_gap_mean_ms'] = timing['pair_gap_sum']*1000/frequency/(operations//2)
        case['pair_gap_max_ms'] = timing['pair_gap_max']*1000/frequency
        case['burst_mean_us'] = timing['burst_sum']*1000000/frequency/case['frames']
        case['burst_max_us'] = timing['burst_max']*1000000/frequency
        case['initial_poll_mean_us'] = timing['initial_sum']*1000000/frequency/case['frames']
        case['initial_poll_max_us'] = timing['initial_max']*1000000/frequency
        case['sizes'] = [sizes[65536], sizes[512]]
    return {'frequency': frequency, 'statistics_queries': [queries[n] for n in range(7)],
            'cases': [cases[n] for n in range(8)],
            'limitations': ['budgets are a synthetic hypothesis, not established title constants',
                            'pump budgets include the initial alertable poll, per-read polls and bookkeeping; oracle/preparation are outside',
                            'frame interval blocks the issuer; CPU-bound frame work is not reproduced',
                            'payload preparation/oracle time is outside submission bursts but within case elapsed time',
                            'native storage completion is not timestamped',
                            'invalid MM Length status and field writes are observations, not prescribed results']}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('serial', type=Path)
    args = parser.parse_args()
    try:
        result = analyze(args.serial.read_text(errors='replace'))
    except (ValueError, KeyError, ZeroDivisionError) as error:
        parser.exit(1, f'invalid burst run: {error}\n')
    print(json.dumps(result, indent=2))

if __name__ == '__main__':
    main()
